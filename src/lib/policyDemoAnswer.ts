type Message = { role: string; content: string };
export function buildPolicyDemoAnswer(question: string, history: Message[] = []): string {
  const prefix = "【演示回答｜非实时模型，未联网核验】\n\n";
  const users = [...history.filter(m => m.role === "user").map(m => m.content), question];
  const context = users.slice(-6).join(" ");
  const topic = /人工智能|大模型|算力/.test(context) ? "人工智能企业" : /人才|博士|落户/.test(context) ? "人才引进" : /专精特新|小巨人/.test(context) ? "专精特新企业" : /研发|高新|科技/.test(context) ? "科技创新企业" : /绿色|低碳|节能/.test(context) ? "绿色低碳项目" : "企业扶持";
  const area = /经开区|亦庄/.test(context) ? "北京经开区" : /北京/.test(context) ? "北京市" : "您所在地区";
  if (/多少|金额|额度|补贴比例|能拿|能领|怎么算/.test(question)) {
    return prefix + `关于${area}${topic}的支持金额，不能仅凭企业行业确定。通常需要逐项核对：\n\n1. 支持对象与资质要求。\n2. 可计入补贴的实际费用或投入。\n3. 补贴比例、单项封顶及年度限制。\n4. 是否与其他政策重复、能否叠加。\n\n比例类事项可按“符合口径的实际金额 × 政策比例”估算，再按政策封顶限制；定额事项则须先确认资质符合。分档奖励和跨年度支持需要单独核算。\n\n请上传政策文件，或提出“帮我测算企业能享受的补贴金额”，使用资金预估表逐项计算。当前没有核验过的具体条款，因此不提供虚构奖励金额。`;
  }
  if (/材料|申请|申报|办理|流程|准备/.test(question)) {
    return prefix + `针对${area}${topic}，可先按以下清单准备申报，具体以当期申报通知为准：\n\n1. 确认主体条件：注册地、行业、资质、信用及政策要求的统计或纳税口径。\n2. 确认事项条件：项目时间、费用范围、验收或认定要求。\n3. 整理证明材料：营业执照、资质证明、项目说明，以及条款要求的合同、发票、付款凭证或审计材料。\n4. 核对申报起止日期、受理部门和提交渠道。\n5. 留存申报回执，并按要求完成补正、审核及后续拨付手续。\n\n这是一份通用准备清单，不是具体政策的正式材料目录。提供政策原文后，才能进一步逐条核对。`;
  }
  if (/条件|符合|资格|可以申请|能申请|享受/.test(question)) {
    return prefix + `判断${area}${topic}能否享受支持，需要同时满足“企业条件”和“事项条件”：\n\n- 企业条件：注册及经营地、企业规模、行业范围、相关资质、信用状况。\n- 事项条件：项目属于支持范围，发生时间及费用口径符合条款，必要的认定或验收已完成。\n- 排除条件：是否存在重复申报、同类支持不得叠加或其他限制。\n\n请补充企业所在地、主营业务、已有资质、拟申报事项及政策文件。当前信息不足以直接认定符合条件。`;
  }
  if (/人工智能|大模型|算力|奖励|补贴|扶持|支持|政策|人才|专精特新|研发|高新|绿色|低碳/.test(question) || /北京|经开区|亦庄|还有|具体|详细|继续/.test(question)) {
    const directions = topic === "人工智能企业"
      ? "1. 研发与技术攻关：关注模型算法、关键技术研发、创新平台等项目类支持。\n2. 算力与数据应用：关注算力使用、数据集建设、技术服务等支持方向。\n3. 应用场景与示范项目：关注人工智能在制造、医疗、交通等领域的落地项目。\n4. 企业培育与人才：关注高新技术、专精特新、人才引进等通用企业支持。"
      : `1. 与${topic}直接相关的专项扶持。\n2. 企业认定、研发投入或成果转化类支持。\n3. 人才、融资及公共服务等配套政策。`;
    return prefix + `您可以从以下方向梳理${area}${topic}可能涉及的支持：\n\n${directions}\n\n这些是政策筛选方向，不表示当前一定存在可申报事项，也不代表已经符合资格。需要进一步核对适用地区、有效期、企业条件和申报通知。\n\n可从官方入口查找原文：中国政府网 https://www.gov.cn/zhengce/ ，北京市政府 https://www.beijing.gov.cn/zhengce/ ，北京经开区管委会 https://kfqgw.beijing.gov.cn/ 。以上为查询入口，并非本次回答的具体政策引用。\n\n您更关心哪一项支持？也可以继续问“需要什么材料”“申请条件是什么”，或提供政策文件进行核对。`;
  }
  return prefix + "当前问题超出预设政策演示范围，暂不能可靠回答。可以咨询企业奖励方向、申报条件、材料清单或资金测算；请同时提供地区和政策原文，避免将通用示例当作正式政策结论。";
}
